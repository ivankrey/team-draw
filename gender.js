// одинаково часто мужские и женские - определяем как мужские, но подсвечиваем
const AMBIGUOUS = new Set(['саша','женя','валя','шура','слава','сима']);

function detectFemale(fullName){
  const tokens = String(fullName).split(/[\s.-]+/).map(norm).filter(Boolean);
  if (!tokens.length) return { female: false, ambiguous: false };

  // 1. точное совпадение по словарю имён
  for (const t of tokens){
    if (AMBIGUOUS.has(t)) return { female: false, ambiguous: true };
    if (FEMALE.has(t)) return { female: true, ambiguous: false };
    if (MALE.has(t)) return { female: false, ambiguous: false };
  }

  // 2. отчество
  for (const t of tokens){
    if (/(овна|евна|ична|инична)$/.test(t)) return { female: true, ambiguous: false };
    if (/(ович|евич|ич)$/.test(t) && t.length > 5) return { female: false, ambiguous: false };
  }

  // 3. фамилия
  for (const t of tokens){
    if (/(ова|ева|ина|ына|ская|цкая|ая|яя)$/.test(t) && t.length > 4) return { female: true, ambiguous: false };
    if (/(ов|ев|ин|ын|ский|цкий|ко|ук|юк|енко|швили|ян)$/.test(t) && t.length > 3) return { female: false, ambiguous: false };
  }

  // 4. окончание имени
  const first = tokens[0];
  if (/(а|я)$/.test(first)) return { female: true, ambiguous: true };

  return { female: false, ambiguous: false };
}
